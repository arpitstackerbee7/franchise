# =====================================================================

def get_erp_details_by_doc_no(doc_no):
    details = empty_erp_details()

    if not doc_no:
        return details

    # Match exact ERPNext document name.
    # The first match is used if a name exists in multiple DocTypes.
    candidates = [
        ("Purchase Receipt", get_from_purchase_receipt),
        ("Purchase Invoice", get_from_purchase_invoice),
        ("Sales Invoice", get_from_sales_invoice),
    ]

    for doctype, handler in candidates:
        if frappe.db.exists(doctype, doc_no):
            try:
                return handler(doc_no)
            except Exception:
                frappe.log_error(
                    title="Advance e-Waybill Log - ERP Lookup Error",
                    message=frappe.get_traceback(),
                )
                return details

    return details



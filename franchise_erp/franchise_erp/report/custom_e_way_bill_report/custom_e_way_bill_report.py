def get_document_type_label(doc_type):
    mapping = {
        "INV": "Invoice",
        "BIL": "Bill",
        "BOE": "Bill of Entry",
        "CHL": "Challan",
        "BOL": "Bill of Lading",
        "OTH": "Others",
        "CNT": "Credit Note",
        "DLC": "Delivery Challan",
        "TAX": "Tax Invoice",
    }

    value = str(doc_type or "").strip()
    return mapping.get(value.upper(), value)



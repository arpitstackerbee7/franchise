def get_from_purchase_receipt(pr_name):
    details = empty_erp_details()

    pr = frappe.db.get_value(
        "Purchase Receipt",
        pr_name,
        [
            "name",
            "posting_date",
            "posting_time",
            "is_return",
            "return_against",
            "custom_gate_entry",
        ],
        as_dict=True,
    )

    if not pr:
        return details

    grc_pr = pr

    if pr.is_return and pr.return_against:
        original_pr = frappe.db.get_value(
            "Purchase Receipt",
            pr.return_against,
            [
                "name",
                "posting_date",
                "posting_time",
                "custom_gate_entry",
            ],
            as_dict=True,
        )

        if original_pr:
            grc_pr = original_pr

    details["grc_prc_no"] = grc_pr.name
    details["grc_prc_date"] = grc_pr.posting_date
    details["grc_prc_time"] = time_value(grc_pr.posting_time)

    gate_entry = (
        getattr(pr, "custom_gate_entry", None)
        or getattr(grc_pr, "custom_gate_entry", None)
    )

    if gate_entry:
        add_gate_entry_details(details, gate_entry)

    add_purchase_invoice_details(details, grc_pr.name)

    return details



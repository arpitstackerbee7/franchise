def empty_erp_details():
    return {
        "gate_in_no": "",
        "gate_in_date": None,
        "gate_in_time": "",
        "logistic_in_no": "",
        "logistic_in_date": None,
        "logistic_in_time": "",
        "grc_prc_no": "",
        "grc_prc_date": None,
        "grc_prc_time": "",
        "purchase_invoice_sales_return_no": "",
        "purchase_invoice_sales_return_date": "",
        "purchase_invoice_sales_return_time": "",
    }


# =====================================================================
# LINKED DOCUMENT CHAIN
#
# E-Way Bill
#   -> Incoming Logistics (submitted; invoice_no = EWB No, else Doc No)
#   -> Gate Entry         (Incoming Logistics.gate_entry_no)
#   -> Purchase Receipt   (Purchase Receipt Item.custom_bulk_gate_entry)
#   -> Purchase Invoice / Sales Return
# =====================================================================

def get_linked_document_details(doc_no, ewb_no=None, from_gstin=None, from_trader_name=None):
    details = empty_erp_details()

    if not doc_no and not ewb_no:
        return details

    # -----------------------------------------------------------------
    # 1. Incoming Logistics (docstatus = 1)
    #    First match EWB No, then fallback to Doc No
    # -----------------------------------------------------------------
    logistics = find_incoming_logistics(
        ewb_no, doc_no, from_gstin, from_trader_name
    )

    if logistics:
        details["logistic_in_no"] = logistics.name
        # Date / time = system creation timestamp of Incoming Logistics
        details["logistic_in_date"], details["logistic_in_time"] = split_datetime(
            logistics.creation
        )

        # -------------------------------------------------------------
        # 2. Gate In No = Incoming Logistics.gate_entry_no
        #    Gate In Date / Time = Gate Entry system creation date / time
        # -------------------------------------------------------------
        gate_entry_no = logistics.gate_entry_no

        if gate_entry_no:
            details["gate_in_no"] = gate_entry_no

            gate = frappe.db.get_value(
                "Gate Entry",
                gate_entry_no,
                ["name", "creation"],
                as_dict=True,
            )

            if gate:
                details["gate_in_date"], details["gate_in_time"] = split_datetime(
                    gate.creation
                )

    # -----------------------------------------------------------------
    # 3. Purchase Receipt through Purchase Receipt Item.custom_bulk_gate_entry
    # -----------------------------------------------------------------
    gate_entry_name = details.get("gate_in_no")

    if gate_entry_name and frappe.db.has_column(
        "Purchase Receipt Item", "custom_bulk_gate_entry"
    ):
        pr_items = frappe.get_all(
            "Purchase Receipt Item",
            filters={"custom_bulk_gate_entry": gate_entry_name},
            fields=["parent"],
            order_by="parent desc",
        )

        pr_names = unique_values([row.parent for row in pr_items])

        if pr_names:
            pr = frappe.db.get_value(
                "Purchase Receipt",
                {
                    "name": ["in", pr_names],
                    "docstatus": ["!=", 2],
                },
                ["name", "posting_date", "posting_time"],
                as_dict=True,
                order_by="posting_date desc, posting_time desc",
            )

            if pr:
                details["grc_prc_no"] = pr.name
                details["grc_prc_date"] = pr.posting_date
                details["grc_prc_time"] = time_value(pr.posting_time)

                # Purchase Invoice linked to this Purchase Receipt
                add_purchase_invoice_details(details, pr.name)

    # -----------------------------------------------------------------
    # 4. If Doc No itself is an ERP document, use its own details
    # -----------------------------------------------------------------
    if doc_no and frappe.db.exists("Purchase Invoice", doc_no):
        apply_purchase_invoice_self(details, doc_no)

    elif doc_no and frappe.db.exists("Sales Invoice", doc_no):
        apply_sales_invoice_links(details, doc_no)

    return details


# =====================================================================
# INCOMING LOGISTICS LOOKUP
# =====================================================================

def find_incoming_logistics(ewb_no, doc_no, from_gstin=None, from_trader_name=None):
    """
    Find a SUBMITTED Incoming Logistics where invoice_no matches:
      1st priority -> EWB No
      2nd priority -> Doc No (only when EWB No gave no match)
    Latest record wins. For Doc No, if several records exist, the one
    whose consignor matches the e-way bill sender is preferred.
    """
    fields = [
        "name",
        "invoice_no",
        "creation",
        "gate_entry_no",
        "consignor",
    ]

    keys = []

    for key in (ewb_no, doc_no):
        key = str(key or "").strip()

        if key and key not in keys:
            keys.append(key)

    for key in keys:
        rows = frappe.get_all(
            "Incoming Logistics",
            filters={"invoice_no": key, "docstatus": 1},
            fields=fields,
            order_by="creation desc",
        )

        if not rows:
            continue

        if len(rows) > 1:
            for row in rows:
                if party_matches(row.get("consignor"), from_gstin, from_trader_name):
                    return row

        return rows[0]

    return None



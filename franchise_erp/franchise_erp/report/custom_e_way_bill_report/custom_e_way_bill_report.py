def get_from_sales_invoice(si_name):
    details = empty_erp_details()

    si = frappe.db.get_value(
        "Sales Invoice",
        si_name,
        [
            "name",
            "posting_date",
            "posting_time",
            "is_return",
            "return_against",
            "custom_gate_entry",
            "custom_outgoing_logistics_reference",
            "custom_outgoing_logistics_no",
        ],
        as_dict=True,
    )

    if not si:
        return details

    if si.is_return:
        details["purchase_invoice_sales_return_no"] = si.name
        details["purchase_invoice_sales_return_date"] = str(si.posting_date or "")
        details["purchase_invoice_sales_return_time"] = time_value(si.posting_time)

    if si.custom_gate_entry:
        add_gate_entry_details(details, si.custom_gate_entry)

    outgoing_logistics = (
        si.custom_outgoing_logistics_reference
        or si.custom_outgoing_logistics_no
    )

    if outgoing_logistics:
        add_sales_returns_from_outgoing_logistics(
            details,
            outgoing_logistics,
        )

    if not si.is_return:
        add_sales_returns_against_sales_invoice(details, si_name)

    return details



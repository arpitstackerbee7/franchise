def get_from_purchase_invoice(pi_name):
    details = empty_erp_details()

    pi = frappe.db.get_value(
        "Purchase Invoice",
        pi_name,
        [
            "name",
            "posting_date",
            "posting_time",
            "is_return",
            "return_against",
            "custom_gate_entry_",
        ],
        as_dict=True,
    )

    if not pi:
        return details

    details["purchase_invoice_sales_return_no"] = pi.name
    details["purchase_invoice_sales_return_date"] = str(pi.posting_date or "")
    details["purchase_invoice_sales_return_time"] = time_value(pi.posting_time)

    gate_entry = getattr(pi, "custom_gate_entry_", None)

    if gate_entry:
        add_gate_entry_details(details, gate_entry)

    pr_names = frappe.get_all(
        "Purchase Invoice Item",
        filters={
            "parent": pi_name,
            "purchase_receipt": ["is", "set"],
        },
        pluck="purchase_receipt",
        order_by="idx asc",
    )

    for pr_name in unique_values(pr_names):
        pr = frappe.db.get_value(
            "Purchase Receipt",
            pr_name,
            [
                "name",
                "posting_date",
                "posting_time",
                "is_return",
                "return_against",
                "custom_gate_entry",
            ],
            as_dict=True,
        )

        if not pr:
            continue

        original_pr = pr

        if pr.is_return and pr.return_against:
            original_pr = frappe.db.get_value(
                "Purchase Receipt",
                pr.return_against,
                [
                    "name",
                    "posting_date",
                    "posting_time",
                    "custom_gate_entry",
                ],
                as_dict=True,
            ) or pr

        details["grc_prc_no"] = original_pr.name
        details["grc_prc_date"] = original_pr.posting_date
        details["grc_prc_time"] = time_value(original_pr.posting_time)

        gate_entry = (
            getattr(original_pr, "custom_gate_entry", None)
            or gate_entry
        )

        if gate_entry:
            add_gate_entry_details(details, gate_entry)

        break

    return details



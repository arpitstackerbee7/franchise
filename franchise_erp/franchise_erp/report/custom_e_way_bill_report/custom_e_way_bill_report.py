def add_sales_returns_against_sales_invoice(details, sales_invoice):
    returns = frappe.get_all(
        "Sales Invoice",
        filters={
            "return_against": sales_invoice,
            "is_return": 1,
            "docstatus": 1,
        },
        fields=[
            "name",
            "posting_date",
            "posting_time",
            "is_return",
        ],
        order_by="posting_date asc, posting_time asc",
    )

    append_transaction_details(details, returns)


# =====================================================================
# SALES RETURNS FROM OUTGOING LOGISTICS

def add_gate_entry_details(details, gate_entry_name):
    gate = frappe.db.get_value(
        "Gate Entry",
        gate_entry_name,
        [
            "name",
            "date",
            "creation",
            "incoming_logistics",
        ],
        as_dict=True,
    )

    if not gate:
        return

    details["gate_in_no"] = gate.name
    details["gate_in_date"] = gate.date or (
        gate.creation.date() if gate.creation else None
    )
    details["gate_in_time"] = (
        gate.creation.time() if gate.creation else None
    )

    if gate.incoming_logistics:
        add_incoming_logistics_details(
            details,
            gate.incoming_logistics,
        )



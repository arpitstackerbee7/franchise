# =====================================================================
# PURCHASE INVOICE FROM PURCHASE RECEIPT
# =====================================================================

def add_purchase_invoice_details(details, pr_name):
    items = frappe.get_all(
        "Purchase Invoice Item",
        filters={"purchase_receipt": pr_name},
        fields=["parent"],
        order_by="parent asc",
    )

    names = unique_values([row.parent for row in items])

    if not names:
        return

    documents = frappe.get_all(
        "Purchase Invoice",
        filters={
            "name": ["in", names],
            "docstatus": 1,
        },
        fields=[
            "name",
            "posting_date",
            "posting_time",
            "is_return",
        ],
        order_by="posting_date asc, posting_time asc",
    )

    append_transaction_details(details, documents)



def unique_values(values):
    result = []
    seen = set()

    for value in values:
        if not value or value in seen:
            continue

        seen.add(value)
        result.append(value)

    return result

def time_value(value):
    if value is None:
        return ""

    try:
        if hasattr(value, "total_seconds"):
            total_seconds = int(value.total_seconds())
            hours = total_seconds // 3600
            minutes = (total_seconds % 3600) // 60
            seconds = total_seconds % 60

            return f"{hours:02d}:{minutes:02d}:{seconds:02d}"

        return str(value)

    except Exception:
        return str(value)
    
    

def get_linked_document_details(doc_no, ewb_no=None):
    details = empty_erp_details()

    if not doc_no and not ewb_no:
        return details

    # 1. Find Gate Entry using E-Way Bill Doc No
    gate_entry = None

    if doc_no:
        gate_entry = frappe.db.get_value(
            "Gate Entry",
            {"document_nos": ["like", f"%{doc_no}%"]},
            ["name", "document_date", "incoming_logistics"],
            as_dict=True,
            order_by="creation desc",
        )

    # 2. Find Incoming Logistics:
    # First match E-Way Bill No, then fallback to Doc No
    logistics = None

    if ewb_no and frappe.db.exists("Incoming Logistics", {"invoice_no": ewb_no}):
        logistics = frappe.db.get_value(
            "Incoming Logistics",
            {"invoice_no": ewb_no},
            ["name", "invoice_date", "invoice_time", "gate_entry_no"],
            as_dict=True,
            order_by="creation desc",
        )

    if not logistics and doc_no:
        logistics = frappe.db.get_value(
            "Incoming Logistics",
            {"invoice_no": doc_no},
            ["name", "invoice_date", "invoice_time", "gate_entry_no"],
            as_dict=True,
            order_by="creation desc",
        )

    # 3. Get Incoming Logistics details and linked Gate Entry
    if logistics:
        details["logistic_in_no"] = logistics.name
        details["logistic_in_date"] = logistics.invoice_date
        details["logistic_in_time"] = str(logistics.invoice_time or "")

        # Prefer Gate Entry linked from Incoming Logistics
        if logistics.gate_entry_no and frappe.db.exists(
            "Gate Entry", logistics.gate_entry_no
        ):
            gate_entry = frappe.db.get_value(
                "Gate Entry",
                logistics.gate_entry_no,
                ["name", "posting_date", "posting_time"],
                as_dict=True,
            )

            if gate_entry:
                details["gate_in_no"] = gate_entry.name
                details["gate_in_date"] = gate_entry.posting_date
                details["gate_in_time"] = str(gate_entry.posting_time or "")

    # Fallback: use Gate Entry found through document_nos
    if gate_entry and not details.get("gate_in_no"):
        details["gate_in_no"] = gate_entry.name
        details["gate_in_date"] = (
            gate_entry.get("posting_date")
            or gate_entry.get("document_date")
        )
        details["gate_in_time"] = str(
            gate_entry.get("posting_time") or ""
        )

    # 4. Purchase Receipt through Purchase Receipt Item.custom_bulk_gate_entry
    gate_entry_name = details.get("gate_in_no")

    if gate_entry_name and frappe.db.has_column(
        "Purchase Receipt Item", "custom_bulk_gate_entry"
    ):
        pr_items = frappe.get_all(
            "Purchase Receipt Item",
            filters={"custom_bulk_gate_entry": gate_entry_name},
            fields=["parent"],
            order_by="parent desc",
        )

        pr_names = unique_values([row.parent for row in pr_items])

        if pr_names:
            pr = frappe.db.get_value(
                "Purchase Receipt",
                {
                    "name": ["in", pr_names],
                    "docstatus": ["!=", 2],
                },
                ["name", "posting_date", "posting_time"],
                as_dict=True,
                order_by="posting_date desc, posting_time desc",
            )

            if pr:
                details["grc_prc_no"] = pr.name
                details["grc_prc_date"] = pr.posting_date
                details["grc_prc_time"] = str(pr.posting_time or "")

                # Purchase Invoice linked to this Purchase Receipt
                add_purchase_invoice_details(details, pr.name)

    # 5. If Doc No itself is an ERP document, use its relationships
    if doc_no and frappe.db.exists("Purchase Invoice", doc_no):
        pi_details = get_from_purchase_invoice(doc_no)

        for key in (
            "purchase_invoice_sales_return_no",
            "purchase_invoice_sales_return_date",
            "purchase_invoice_sales_return_time",
        ):
            if pi_details.get(key):
                details[key] = pi_details[key]

    elif doc_no and frappe.db.exists("Sales Invoice", doc_no):
        si_details = get_from_sales_invoice(doc_no)

        for key in (
            "purchase_invoice_sales_return_no",
            "purchase_invoice_sales_return_date",
            "purchase_invoice_sales_return_time",
        ):
            if si_details.get(key):
                details[key] = si_details[key]

    return details
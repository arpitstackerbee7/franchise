# PURCHASE INVOICE FROM PURCHASE RECEIPT
# =====================================================================

def add_purchase_invoice_details(details, pr_name):
    items = frappe.get_all(
        "Purchase Invoice Item",
        filters={"purchase_receipt": pr_name},
        fields=["parent"],
        order_by="parent asc",
    )

    names = unique_values([row.parent for row in items])

    if not names:
        return

    documents = frappe.get_all(
        "Purchase Invoice",
        filters={
            "name": ["in", names],
            "docstatus": 1,
        },
        fields=[
            "name",
            "posting_date",
            "posting_time",
            "is_return",
        ],
        order_by="posting_date asc, posting_time asc",
    )

    append_transaction_details(details, documents)


# =====================================================================
# DOC NO IS A PURCHASE INVOICE
# =====================================================================

def apply_purchase_invoice_self(details, pi_name):
    pi = frappe.db.get_value(
        "Purchase Invoice",
        pi_name,
        ["name", "posting_date", "posting_time"],
        as_dict=True,
    )

    if not pi:
        return

    details["purchase_invoice_sales_return_no"] = pi.name
    details["purchase_invoice_sales_return_date"] = str(pi.posting_date or "")
    details["purchase_invoice_sales_return_time"] = time_value(pi.posting_time)


# =====================================================================
# DOC NO IS A SALES INVOICE
# =====================================================================

def apply_sales_invoice_links(details, si_name):
    si = frappe.db.get_value(
        "Sales Invoice",
        si_name,
        [
            "name",
            "posting_date",
            "posting_time",
            "is_return",
            "custom_outgoing_logistics_reference",
            "custom_outgoing_logistics_no",
        ],
        as_dict=True,
    )

    if not si:
        return

    # Start from a clean slate for the PI / Sales Return columns
    details["purchase_invoice_sales_return_no"] = ""
    details["purchase_invoice_sales_return_date"] = ""
    details["purchase_invoice_sales_return_time"] = ""

    if si.is_return:
        details["purchase_invoice_sales_return_no"] = si.name
        details["purchase_invoice_sales_return_date"] = str(si.posting_date or "")
        details["purchase_invoice_sales_return_time"] = time_value(si.posting_time)

    outgoing_logistics = (
        si.custom_outgoing_logistics_reference
        or si.custom_outgoing_logistics_no
    )

    if outgoing_logistics:
        add_sales_returns_from_outgoing_logistics(details, outgoing_logistics)

    if not si.is_return:
        add_sales_returns_against_sales_invoice(details, si_name)


# =====================================================================
# SALES RETURNS AGAINST SALES INVOICE

def add_sales_returns_from_outgoing_logistics(details, outgoing_logistics):
    returns = frappe.get_all(
        "Sales Invoice",
        filters={
            "custom_outgoing_logistics_reference": outgoing_logistics,
            "is_return": 1,
            "docstatus": 1,
        },
        fields=[
            "name",
            "posting_date",
            "posting_time",
            "is_return",
        ],
        order_by="posting_date asc, posting_time asc",
    )

    append_transaction_details(details, returns)


# =====================================================================
# APPEND PI / SALES RETURN DETAILS
# =====================================================================

def append_transaction_details(details, documents):
    if not documents:
        return

    unique_documents = []
    seen = set()

    for doc in documents:
        if doc.name in seen:
            continue

        seen.add(doc.name)
        unique_documents.append(doc)

    def merge(key, values):
        existing = [
            value.strip()
            for value in str(details.get(key) or "").split(",")
            if value.strip()
        ]

        for value in values:
            if value and value not in existing:
                existing.append(value)

        details[key] = ", ".join(existing)

    merge(
        "purchase_invoice_sales_return_no",
        [doc.name for doc in unique_documents],
    )
    merge(
        "purchase_invoice_sales_return_date",
        [str(doc.posting_date) for doc in unique_documents if doc.posting_date],
    )
    merge(
        "purchase_invoice_sales_return_time",
        [time_value(doc.posting_time) for doc in unique_documents],
    )


# =====================================================================
# PARTY MATCH (used only to pick the best Incoming Logistics when
# several records share the same Doc No)
# =====================================================================

def normalize_name(value):
    import re

    return re.sub(r"[^a-z0-9]", "", str(value or "").lower())


def party_matches(party, from_gstin, from_trader_name):
    if not party:
        return False

    target_name = normalize_name(from_trader_name)
    target_gstin = str(from_gstin or "").strip().upper()

    # 1. GSTIN match (most reliable)
    if target_gstin and frappe.db.has_column("Supplier", "gstin"):
        party_gstin = frappe.db.get_value("Supplier", party, "gstin")

        if party_gstin and str(party_gstin).strip().upper() == target_gstin:
            return True

    # 2. Name match (ignores case, spaces, punctuation)
    party_name = normalize_name(party)

    if party_name and target_name:
        if (
            party_name == target_name
            or party_name in target_name
            or target_name in party_name
        ):
            return True

    return False



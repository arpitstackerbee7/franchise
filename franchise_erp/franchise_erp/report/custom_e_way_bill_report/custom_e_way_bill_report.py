# =====================================================================
# APPEND PI / SALES RETURN DETAILS
# =====================================================================

def append_transaction_details(details, documents):
    if not documents:
        return

    unique_documents = []
    seen = set()

    for doc in documents:
        if doc.name in seen:
            continue
        seen.add(doc.name)
        unique_documents.append(doc)

    # Document numbers
    key = "purchase_invoice_sales_return_no"
    existing = [
        value.strip()
        for value in str(details[key] or "").split(",")
        if value.strip()
    ]

    for doc in unique_documents:
        if doc.name not in existing:
            existing.append(doc.name)

    details[key] = ", ".join(existing)

    # Document dates
    key = "purchase_invoice_sales_return_date"
    existing = [
        value.strip()
        for value in str(details[key] or "").split(",")
        if value.strip()
    ]

    for doc in unique_documents:
        if not doc.posting_date:
            continue

        value = str(doc.posting_date)
        if value not in existing:
            existing.append(value)

    details[key] = ", ".join(existing)

    # Document times
    key = "purchase_invoice_sales_return_time"
    existing = [
        value.strip()
        for value in str(details[key] or "").split(",")
        if value.strip()
    ]

    for doc in unique_documents:
        value = time_value(doc.posting_time)
        if value and value not in existing:
            existing.append(value)

    details[key] = ", ".join(existing)



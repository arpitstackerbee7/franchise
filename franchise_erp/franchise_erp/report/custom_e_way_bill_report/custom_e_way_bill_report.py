def get_data(filters):
    fields = [
        "name",
        "ewb_no",
        "ewb_date",
        "supply_type",
        "sub_supply_type",
        "doc_no",
        "doc_date",
        "doc_type",
        "generated_by",
        "from_gstin",
        "from_trader_name",
        "from_address",
        "from_place",
        "from_pincode",
        "to_gstin",
        "to_trader_name",
        "to_address",
        "to_place",
        "to_pincode",
        "status",
        "no_of_items",
        "main_hsn_code",
        "hsn_desc",
        "assessable_value",
        "sgst_value",
        "cgst_value",
        "igst_value",
        "cess_value",
        "cess_non_advol_value",
        "other_value",
        "total_invvalue",
        "valid_till_date",
        "mode_of_gen",
        "irn",
        "source",
    ]

    logs = frappe.get_all(
        "Advance e-Waybill Log",
        fields=fields,
        order_by="ewb_date desc",
    )

    result = []

    for log in logs:
        ewb_no = log.ewb_no or ""

        ewb_date = log.ewb_date
        doc_date = log.doc_date

        # -------------------------------------------------------------
        # FILTER: EWB NO
        # Existing filter fieldname: eway_bill_no
        # -------------------------------------------------------------

        filter_ewb_no = filters.get("eway_bill_no")

        if filter_ewb_no:
            if str(filter_ewb_no).strip().lower() not in str(ewb_no).lower():
                continue

        # -------------------------------------------------------------
        # FILTER: EWB DATE
        # Existing filter fieldname: eway_bill_date
        # -------------------------------------------------------------

        filter_date = filters.get("eway_bill_date")

        if filter_date:
            if not ewb_date:
                continue

            if getdate(ewb_date) != getdate(filter_date):
                continue

        # -------------------------------------------------------------
        # FILTER: DOC TYPE
        # -------------------------------------------------------------

        filter_doc_type = filters.get("doc_type")

        if filter_doc_type:
            if str(filter_doc_type).strip().lower() not in (
                str(log.doc_type or "").strip().lower(),
                get_document_type_label(log.doc_type).strip().lower(),
            ):
                continue

        # -------------------------------------------------------------
        # FILTER: DOC NO
        # -------------------------------------------------------------

        filter_doc_no = filters.get("doc_no")

        if filter_doc_no:
            if str(filter_doc_no).strip().lower() not in str(log.doc_no or "").lower():
                continue

        # -------------------------------------------------------------
        # OTHER PARTY GSTIN
        #
        # Inward: supplier/from party
        # Outward: recipient/to party
        # -------------------------------------------------------------

        supply_type = str(log.supply_type or "").strip().lower()

        if supply_type in ("inward", "i"):
            other_party_gstin = log.from_gstin or ""
        elif supply_type in ("outward", "o"):
            other_party_gstin = log.to_gstin or ""
        else:
            other_party_gstin = ""

        # -------------------------------------------------------------
        # ERP DOCUMENT CHAIN
        #
        # Advance e-Waybill Log does not have reference_doctype or
        # reference_name. Therefore, try to identify the ERP document
        # by matching Doc No against known ERPNext document names.
        # -------------------------------------------------------------

        erp_details = get_linked_document_details(
            log.doc_no,
            log.ewb_no,
        )

        result.append({
            "ewb_no": ewb_no,
            "ewb_date": ewb_date,
            "supply_type": log.supply_type,
            "sub_supply_type": log.sub_supply_type,
            "doc_no": log.doc_no,
            "doc_date": doc_date,
            "doc_type": get_document_type_label(log.doc_type),
            "generated_by": log.generated_by,
            "from_gstin": log.from_gstin,
            "from_trader_name": log.from_trader_name,
            "from_address": log.from_address,
            "from_place": log.from_place,
            "from_pincode": log.from_pincode,
            "to_gstin": log.to_gstin,
            "to_trader_name": log.to_trader_name,
            "to_address": log.to_address,
            "to_place": log.to_place,
            "to_pincode": log.to_pincode,
            "other_party_gstin": other_party_gstin,
            "status": log.status,
            "no_of_items": log.no_of_items,
            "main_hsn_code": log.main_hsn_code,
            "hsn_desc": log.hsn_desc,
            "assessable_value": flt(log.assessable_value),
            "sgst_value": flt(log.sgst_value),
            "cgst_value": flt(log.cgst_value),
            "igst_value": flt(log.igst_value),
            "cess_value": flt(log.cess_value),
            "cess_non_advol_value": flt(log.cess_non_advol_value),
            "other_value": flt(log.other_value),
            "total_invvalue": flt(log.total_invvalue),
            "valid_till_date": log.valid_till_date,
            "mode_of_gen": log.mode_of_gen,
            "irn": log.irn,
            "source": log.source,

            "gate_in_no": erp_details["gate_in_no"],
            "gate_in_date": erp_details["gate_in_date"],
            "gate_in_time": erp_details["gate_in_time"],
            "logistic_in_no": erp_details["logistic_in_no"],
            "logistic_in_date": erp_details["logistic_in_date"],
            "logistic_in_time": erp_details["logistic_in_time"],
            "grc_prc_no": erp_details["grc_prc_no"],
            "grc_prc_date": erp_details["grc_prc_date"],
            "grc_prc_time": erp_details["grc_prc_time"],
            "purchase_invoice_sales_return_no":
                erp_details["purchase_invoice_sales_return_no"],
            "purchase_invoice_sales_return_date":
                erp_details["purchase_invoice_sales_return_date"],
            "purchase_invoice_sales_return_time":
                erp_details["purchase_invoice_sales_return_time"],
        })

    return result


